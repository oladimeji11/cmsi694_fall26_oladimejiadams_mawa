import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:mawa_app/screens/llm_test_screen.dart';
import 'package:mawa_app/services/llm_service.dart';

class FakeLlmService extends LlmService {
  final String mockReply;
  final String mockModel;
  final bool mockHasApiKey;

  FakeLlmService({
    this.mockReply = 'Stay safe during hot weather in Los Angeles.',
    this.mockModel = 'google/gemma-4-31b-it:free',
    this.mockHasApiKey = true,
  });

  @override
  bool get hasApiKey => mockHasApiKey;

  @override
  Future<LlmResult> sendTestPrompt({
    String prompt = LlmService.defaultTestPrompt,
    String? targetModel,
  }) async {
    return LlmResult(
      text: mockReply,
      activeModel: mockModel,
      isSuccess: true,
    );
  }
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  Widget buildTestableWidget(Widget child) {
    return MaterialApp(
      home: child,
    );
  }

  testWidgets('LlmTestScreen renders model metadata, prompt, and API key status',
      (WidgetTester tester) async {
    final fakeLlmService = FakeLlmService();

    await tester.pumpWidget(
      buildTestableWidget(
        LlmTestScreen(llmService: fakeLlmService),
      ),
    );
    await tester.pumpAndSettle();

    expect(find.text('AI Connection Test'), findsOneWidget);
    expect(find.text(LlmService.modelName), findsOneWidget);
    expect(find.text(LlmService.providerName), findsOneWidget);
    expect(find.text('Configured via --dart-define'), findsOneWidget);
    expect(find.text(LlmService.defaultTestPrompt), findsOneWidget);
    expect(find.text('Contains zero personal user data.'), findsOneWidget);
  });

  testWidgets('Tapping Send Test Prompt displays AI model reply and model label badge',
      (WidgetTester tester) async {
    final fakeLlmService = FakeLlmService(
      mockReply: 'AI model test response: Stay hydrated in LA.',
      mockModel: 'google/gemma-4-31b-it:free',
    );

    await tester.pumpWidget(
      buildTestableWidget(
        LlmTestScreen(llmService: fakeLlmService),
      ),
    );
    await tester.pumpAndSettle();

    final sendButton = find.widgetWithText(ElevatedButton, 'Send Test Prompt to AI Model');
    expect(sendButton, findsOneWidget);

    await tester.tap(sendButton);
    await tester.pumpAndSettle();

    expect(find.text('Generated by: google/gemma-4-31b-it:free'), findsOneWidget);
    expect(
      find.text('AI model test response: Stay hydrated in LA.'),
      findsOneWidget,
    );
  });
}
